"""Generate ``wirelet.schema`` from Telegram's TL schema.

Run ``python -m compiler`` from the repository root. Output goes to
``wirelet/schema/{methods,objects,kinds}`` and ``wirelet/schema/registry.py``.
None of it is edited by hand: update ``compiler/schema/*.tl`` and regenerate.

Naming in the output:

* ``schema.methods``  - every API method (``messages.sendMessage`` ->
  ``schema.methods.messages.SendMessage``)
* ``schema.objects``  - every constructor (``user`` -> ``schema.objects.User``)
* ``schema.kinds``    - the abstract types constructors belong to, for
  ``isinstance`` checks (``schema.kinds.InputPeer``)
"""

from __future__ import annotations

import keyword
import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_DIR = Path(__file__).resolve().parent / "schema"
OUT_DIR = ROOT / "wirelet" / "schema"
GENERATED = ("methods", "objects", "kinds")

# Primitives handled by hand in wirelet.schema.core. (MTProto's rpc_result,
# msg_container and gzip_packed are commented out in the schema itself.)
SKIPPED = {"boolFalse", "boolTrue", "true", "vector"}

# In mtproto.tl "string" fields carry binary data (pq, g_a, encrypted_answer,
# ...). Both encode the same on the wire, so they are bytes there; these few
# really are text.
MTPROTO_TEXT_FIELDS = {("rpc_error", "error_message")}

LINE_RE = re.compile(
    r"^(?P<name>[\w.]+)#(?P<id>[0-9a-fA-F]{1,8})\s*(?P<generic>\{X:Type\})?\s*"
    r"(?P<args>.*?)\s*=\s*(?P<type>[\w.<> ]+);$"
)
ARG_RE = re.compile(r"(?P<name>\w+):(?P<type>[\w.<>!#?]+)")
FLAG_RE = re.compile(r"^(?P<flag>\w+)\.(?P<bit>\d+)\?(?P<type>.+)$")
LAYER_RE = re.compile(r"//\s*LAYER\s+(\d+)")

HEADER = """#  Generated by compiler/tl.py from Telegram's TL schema (layer {layer}).
#  Do not edit by hand: change compiler/schema/*.tl and regenerate.
"""


@dataclass
class Field:
    tl: str                    # name in the schema
    py: str                    # Python identifier
    type: str                  # TL type without the flag prefix
    flag: Optional[str] = None
    bit: Optional[int] = None

    @property
    def is_flags(self) -> bool:
        return self.type == "#"

    @property
    def optional(self) -> bool:
        return self.flag is not None


@dataclass
class Entry:
    tl: str
    cid: int
    fields: List[Field]
    result: str
    is_method: bool
    generic: bool
    namespace: str
    py: str

    @property
    def section(self) -> str:
        return "methods" if self.is_method else "objects"

    @property
    def name(self) -> str:
        ns = f"{self.namespace}." if self.namespace else ""
        return f"{self.section}.{ns}{self.py}"


def pascal(name: str) -> str:
    """``p_q_inner_data`` -> ``PQInnerData``; ``inputPeerUser`` -> ``InputPeerUser``."""
    return "".join(part[:1].upper() + part[1:] for part in name.split("_") if part)


def split_ns(name: str):
    return tuple(name.split(".", 1)) if "." in name else ("", name)


def identifier(name: str) -> str:
    if name == "self":
        return "is_self"
    return name + "_" if keyword.iskeyword(name) else name


def parse(text: str, binary_strings: bool = False) -> List[Entry]:
    is_method = False
    out = []

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if line == "---functions---":
            is_method = True
            continue
        if line == "---types---":
            is_method = False
            continue
        if not line or line.startswith("//"):
            continue

        m = LINE_RE.match(line)
        if not m or m.group("name") in SKIPPED:
            continue
        tl = m.group("name")

        fields = []
        for am in ARG_RE.finditer(m.group("args")):
            fname, ftype = am.group("name"), am.group("type")
            if binary_strings and (tl, fname) not in MTPROTO_TEXT_FIELDS:
                ftype = re.sub(r"\bstring\b", "bytes", ftype)
            fm = FLAG_RE.match(ftype)
            if fm:
                fields.append(Field(fname, identifier(fname), fm.group("type"),
                                    fm.group("flag"), int(fm.group("bit"))))
            else:
                fields.append(Field(fname, identifier(fname), ftype))

        ns, short = split_ns(tl)
        out.append(Entry(
            tl=tl, cid=int(m.group("id"), 16), fields=fields, result=m.group("type").strip(),
            is_method=is_method, generic=m.group("generic") is not None,
            namespace=ns, py=pascal(short),
        ))
    return out


# --------------------------------------------------------------------------- #
# Types
# --------------------------------------------------------------------------- #

PRIMITIVES = {
    "int": ("I32", "int"),
    "long": ("I64", "int"),
    "int128": ("I128", "int"),
    "int256": ("I256", "int"),
    "double": ("F64", "float"),
    "string": ("Text", "str"),
    "bytes": ("Blob", "bytes"),
    "Bool": ("Boolean", "bool"),
}


def seq_item(t: str) -> Optional[str]:
    for prefix in ("Vector<", "vector<"):
        if t.startswith(prefix) and t.endswith(">"):
            return t[len(prefix):-1]
    return None


def kind_ref(t: str) -> str:
    ns, short = split_ns(t)
    return f"schema.kinds.{ns + '.' if ns else ''}{pascal(short)}"


def hint(t: str) -> str:
    if t in PRIMITIVES:
        return PRIMITIVES[t][1]
    if t == "true":
        return "bool"
    if t == "!X":
        return "Struct"
    item = seq_item(t)
    if item is not None:
        return f"List[{hint(item)}]"
    return f'"{kind_ref(t)}"'


def decoder(t: str) -> str:
    """An expression of a callable ``f(stream) -> value``."""
    if t in PRIMITIVES:
        return f"{PRIMITIVES[t][0]}.decode"
    item = seq_item(t)
    if item is not None:
        return f"lambda s: Seq.decode(s, {decoder(item)})"
    return "Struct.decode"


def decode_expr(t: str) -> str:
    if t in PRIMITIVES:
        return f"{PRIMITIVES[t][0]}.decode(s)"
    item = seq_item(t)
    if item is not None:
        return f"Seq.decode(s, {decoder(item)})"
    return "Struct.decode(s)"


def encoder(t: str) -> str:
    """An expression of a callable ``f(value) -> bytes``."""
    if t in PRIMITIVES:
        return PRIMITIVES[t][0]
    item = seq_item(t)
    if item is not None:
        return f"lambda v: Seq(v, {encoder(item)})"
    return "encode_struct"


def encode_expr(t: str, value: str) -> str:
    if t in PRIMITIVES:
        return f"{PRIMITIVES[t][0]}({value})"
    item = seq_item(t)
    if item is not None:
        return f"Seq({value}, {encoder(item)})"
    return f"{value}.encode()"


# --------------------------------------------------------------------------- #
# Code generation
# --------------------------------------------------------------------------- #

def gen_class(e: Entry) -> str:
    values = [f for f in e.fields if not f.is_flags]
    required = [f for f in values if not f.optional]
    optional = [f for f in values if f.optional]

    bases = ["Struct"] if e.is_method else [kind_ref(e.result).replace("schema.kinds", "_kinds"), "Struct"]
    what = "method" if e.is_method else "object"
    tail = f"Returns ``{e.result}``." if e.is_method else f"A kind of ``{e.result}``."

    out = [
        f"class {e.py}({', '.join(bases)}):",
        f'    """Telegram API {what} ``{e.tl}`` (0x{e.cid:08x}). {tail}"""',
        "",
        f"    __slots__ = ({''.join(repr(f.py) + ', ' for f in values)})",
        "",
        f"    CID = 0x{e.cid:08x}",
        f'    NAME = "{e.name}"',
        f'    TL = "{e.tl}"',
    ]
    if e.is_method:
        out.append(f'    RETURNS = "{e.result}"')
    out.append("")

    params = [f"{f.py}: {hint(f.type)}" for f in required]
    params += [f"{f.py}: Optional[{'bool' if f.type == 'true' else hint(f.type)}] = None" for f in optional]
    out.append(f"    def __init__({', '.join(['self'] + (['*'] + params if params else []))}) -> None:")
    out += [f"        self.{f.py} = {f.py}" for f in values] or ["        pass"]
    out.append("")

    out.append("    @staticmethod")
    out.append(f'    def decode(s: BytesIO, *args: Any) -> "{e.py}":')
    for f in e.fields:
        if f.is_flags:
            out.append(f"        f_{f.tl} = I32.decode(s)")
        elif f.optional:
            mask = f"f_{f.flag} & {1 << f.bit}"
            if f.type == "true":
                out.append(f"        v_{f.py} = bool({mask})")
            else:
                out.append(f"        v_{f.py} = {decode_expr(f.type)} if {mask} else None")
        else:
            out.append(f"        v_{f.py} = {decode_expr(f.type)}")
    out.append(f"        return {e.py}({', '.join(f'{f.py}=v_{f.py}' for f in values)})")
    out.append("")

    out.append("    def encode(self) -> bytes:")
    out.append("        s = BytesIO()")
    out.append("        s.write(I32(self.CID, False))")
    for f in e.fields:
        if f.is_flags:
            out.append(f"        f_{f.tl} = 0")
            for x in optional:
                if x.flag != f.tl:
                    continue
                test = f"self.{x.py}" if x.type == "true" else f"self.{x.py} is not None"
                out.append(f"        if {test}:")
                out.append(f"            f_{f.tl} |= {1 << x.bit}")
            out.append(f"        s.write(I32(f_{f.tl}))")
        elif f.optional:
            if f.type != "true":
                out.append(f"        if self.{f.py} is not None:")
                out.append(f"            s.write({encode_expr(f.type, 'self.' + f.py)})")
        else:
            out.append(f"        s.write({encode_expr(f.type, 'self.' + f.py)})")
    out.append("        return s.getvalue()")

    if e.is_method:
        out.append("")
        out.append("    def decode_result(self, s: BytesIO) -> Any:")
        item = seq_item(e.result)
        if e.generic:
            out.append("        return decode_result(s, self.query)")
        elif item is not None:
            out.append(f"        return decode_result(s, item={decoder(item)})")
        elif e.result in PRIMITIVES:
            out.append(f"        return decode_result(s, primitive={PRIMITIVES[e.result][0]}.decode)")
        else:
            out.append("        return decode_result(s)")

    return "\n".join(out)


def module_header(layer: int, section: str) -> str:
    lines = [
        HEADER.format(layer=layer),
        "# flake8: noqa",
        "from __future__ import annotations",
        "",
        "from io import BytesIO",
        "from typing import TYPE_CHECKING, Any, List, Optional",
        "",
        "from wirelet.schema.core import (",
        "    Struct, I32, I64, I128, I256, F64, Text, Blob, Boolean, Seq,",
        "    decode_result, encode_struct,",
        ")",
    ]
    if section == "objects":
        lines.append("from wirelet.schema import kinds as _kinds")
    lines += ["", "if TYPE_CHECKING:", "    from wirelet import schema", ""]
    return "\n".join(lines)


def gen_kinds_module(layer: int, names: Dict[str, List[str]], ns: str) -> str:
    out = [HEADER.format(layer=layer), "# flake8: noqa", ""]
    prefix = f"{ns}." if ns else ""
    for name in sorted(names):
        out += [
            f"class {name}:",
            f'    """Abstract type ``{prefix}{name}``: {", ".join(sorted(names[name]))}."""',
            "",
            "    __slots__ = ()",
            f'    NAME = "kinds.{prefix}{name}"',
            "",
            "",
        ]
    return "\n".join(out)


def write_package(pkg: Path, modules: Dict[str, str], layer: int) -> None:
    pkg.mkdir(parents=True, exist_ok=True)
    root = modules.pop("", None) or HEADER.format(layer=layer)
    init = root.rstrip() + "\n"
    if modules:
        init += f"\n\nfrom . import {', '.join(sorted(modules))}  # noqa: E402\n"
    (pkg / "__init__.py").write_text(init)
    for name, body in modules.items():
        (pkg / f"{name}.py").write_text(body)


def build() -> int:
    api = (SCHEMA_DIR / "api.tl").read_text(encoding="utf-8")
    mtproto = (SCHEMA_DIR / "mtproto.tl").read_text(encoding="utf-8")

    found = LAYER_RE.search(api)
    if not found:
        raise SystemExit("api.tl has no '// LAYER N' line")
    layer = int(found.group(1))

    entries: Dict[str, Entry] = {}
    for e in parse(mtproto, binary_strings=True) + parse(api):
        entries[e.tl] = e  # api.tl wins a clash

    seen = {}
    for e in entries.values():
        key = (e.section, e.namespace, e.py)
        if key in seen:
            raise SystemExit(f"Name clash: {e.tl} and {seen[key]}")
        seen[key] = e.tl

    for sub in GENERATED:
        shutil.rmtree(OUT_DIR / sub, ignore_errors=True)

    kinds: Dict[str, Dict[str, List[str]]] = {}
    for e in entries.values():
        if not e.is_method:
            ns, short = split_ns(e.result)
            kinds.setdefault(ns, {}).setdefault(pascal(short), []).append(e.py)
    write_package(OUT_DIR / "kinds", {ns: gen_kinds_module(layer, n, ns) for ns, n in kinds.items()}, layer)

    for section in ("objects", "methods"):
        by_ns: Dict[str, List[Entry]] = {}
        for e in entries.values():
            if e.section == section:
                by_ns.setdefault(e.namespace, []).append(e)
        modules = {
            ns: "\n\n".join([module_header(layer, section)]
                            + [gen_class(e) + "\n\n" for e in sorted(items, key=lambda x: x.py)])
            for ns, items in by_ns.items()
        }
        write_package(OUT_DIR / section, modules, layer)

    reg = [HEADER.format(layer=layer), f"LAYER = {layer}", "", "# constructor id -> dotted name under wirelet.schema", "NAMES = {"]
    reg += [f'    0x{e.cid:08x}: "{e.name}",' for e in sorted(entries.values(), key=lambda e: e.cid)]
    reg.append("}")
    (OUT_DIR / "registry.py").write_text("\n".join(reg) + "\n")

    n_objects = sum(1 for e in entries.values() if not e.is_method)
    print(f"wirelet: generated layer {layer}: {n_objects} objects, {len(entries) - n_objects} methods")
    return layer


if __name__ == "__main__":
    build()
