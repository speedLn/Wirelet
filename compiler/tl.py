"""Generate ``wirelet.raw`` from Telegram's TL schema.

Run ``python -m compiler`` from the repository root. The output is written to
``wirelet/raw/{types,functions,base}`` and ``wirelet/raw/all.py``; none of it is
hand-edited, so update the schema in ``compiler/schema`` and regenerate instead.
"""

from __future__ import annotations

import keyword
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_DIR = Path(__file__).resolve().parent / "schema"
OUT_DIR = ROOT / "wirelet" / "raw"

# Primitives parsed by hand in wirelet.raw.core. (MTProto's rpc_result,
# msg_container and gzip_packed are commented out in the schema itself.)
SKIPPED = {"boolFalse", "boolTrue", "true", "vector"}

LINE_RE = re.compile(
    r"^(?P<name>[\w.]+)#(?P<id>[0-9a-fA-F]{1,8})\s*(?P<generic>\{X:Type\})?\s*"
    r"(?P<args>.*?)\s*=\s*(?P<type>[\w.<> ]+);$"
)
ARG_RE = re.compile(r"(?P<name>\w+):(?P<type>[\w.<>!#?]+)")
FLAG_RE = re.compile(r"^(?P<flag>\w+)\.(?P<bit>\d+)\?(?P<type>.+)$")
LAYER_RE = re.compile(r"//\s*LAYER\s+(\d+)")

HEADER = '''#  Generated by compiler/tl.py from Telegram's TL schema (layer {layer}).
#  Do not edit by hand: change the schema and regenerate.
'''


@dataclass
class Arg:
    name: str          # TL name
    py: str            # Python identifier
    type: str          # TL type with the flag prefix removed
    flag: Optional[str] = None
    bit: Optional[int] = None

    @property
    def is_flags(self) -> bool:
        return self.type == "#"

    @property
    def optional(self) -> bool:
        return self.flag is not None


@dataclass
class Combinator:
    tl_name: str
    id: int
    args: List[Arg]
    result: str
    is_function: bool
    generic: bool = False
    namespace: str = ""
    py_name: str = ""
    section: str = field(default="types")

    @property
    def qualname(self) -> str:
        ns = f"{self.namespace}." if self.namespace else ""
        return f"{self.section}.{ns}{self.py_name}"


def camel(name: str) -> str:
    """``p_q_inner_data`` -> ``PQInnerData``; ``inputPeerUser`` -> ``InputPeerUser``."""
    return "".join(part[:1].upper() + part[1:] for part in name.split("_") if part)


def split_ns(name: str):
    if "." in name:
        ns, short = name.split(".", 1)
        return ns, short
    return "", name


def py_ident(name: str) -> str:
    if name == "self":
        return "is_self"
    if keyword.iskeyword(name):
        return name + "_"
    return name


# In mtproto.tl "string" fields carry binary data (pq, g_a, encrypted_answer,
# ...). Both encode the same on the wire, so read them as bytes there; these are
# the few that really are text.
MTPROTO_TEXT_FIELDS = {("rpc_error", "error_message")}


def parse(text: str, initial_section: str, binary_strings: bool = False) -> List[Combinator]:
    section = initial_section
    out = []

    for raw_line in text.splitlines():
        line = raw_line.strip()

        if line == "---functions---":
            section = "functions"
            continue
        if line == "---types---":
            section = "types"
            continue
        if not line or line.startswith("//"):
            continue

        m = LINE_RE.match(line)
        if not m:
            continue

        name = m.group("name")
        if name in SKIPPED:
            continue

        args = []
        for am in ARG_RE.finditer(m.group("args")):
            arg_name, arg_type = am.group("name"), am.group("type")
            if binary_strings and (name, arg_name) not in MTPROTO_TEXT_FIELDS:
                arg_type = re.sub(r"\bstring\b", "bytes", arg_type)
            fm = FLAG_RE.match(arg_type)
            if fm:
                args.append(Arg(arg_name, py_ident(arg_name), fm.group("type"),
                                fm.group("flag"), int(fm.group("bit"))))
            else:
                args.append(Arg(arg_name, py_ident(arg_name), arg_type))

        ns, short = split_ns(name)
        out.append(Combinator(
            tl_name=name,
            id=int(m.group("id"), 16),
            args=args,
            result=m.group("type").strip(),
            is_function=section == "functions",
            generic=m.group("generic") is not None,
            namespace=ns,
            py_name=camel(short),
            section="functions" if section == "functions" else "types",
        ))

    return out


# --------------------------------------------------------------------------- #
# Type mapping
# --------------------------------------------------------------------------- #

PRIMITIVES = {
    "int": ("Int", "int"),
    "long": ("Long", "int"),
    "int128": ("Int128", "int"),
    "int256": ("Int256", "int"),
    "double": ("Double", "float"),
    "string": ("String", "str"),
    "bytes": ("Bytes", "bytes"),
    "Bool": ("Bool", "bool"),
}


def vector_inner(t: str) -> Optional[str]:
    for prefix in ("Vector<", "vector<"):
        if t.startswith(prefix) and t.endswith(">"):
            return t[len(prefix):-1]
    return None


def base_ref(t: str) -> str:
    ns, short = split_ns(t)
    return f"raw.base.{ns + '.' if ns else ''}{camel(short)}"


def hint(t: str) -> str:
    if t in PRIMITIVES:
        return PRIMITIVES[t][1]
    if t == "true":
        return "bool"
    if t == "!X":
        return "TLObject"
    inner = vector_inner(t)
    if inner is not None:
        return f"List[{hint(inner)}]"
    return f'"{base_ref(t)}"'


def reader(t: str) -> str:
    """An expression of a callable ``f(b) -> value`` for type ``t``."""
    if t in PRIMITIVES:
        return f"{PRIMITIVES[t][0]}.read"
    inner = vector_inner(t)
    if inner is not None:
        return f"lambda b: Vector.read(b, {reader(inner)})"
    return "TLObject.read"


def read_expr(t: str) -> str:
    if t in PRIMITIVES:
        return f"{PRIMITIVES[t][0]}.read(b)"
    if t == "!X":
        return "TLObject.read(b)"
    inner = vector_inner(t)
    if inner is not None:
        return f"Vector.read(b, {reader(inner)})"
    return "TLObject.read(b)"


def writer(t: str) -> str:
    """An expression of a callable ``f(value) -> bytes`` for type ``t``."""
    if t in PRIMITIVES:
        return PRIMITIVES[t][0]
    inner = vector_inner(t)
    if inner is not None:
        return f"lambda v: Vector(v, {writer(inner)})"
    return "write_object"


def write_expr(t: str, value: str) -> str:
    if t in PRIMITIVES:
        return f"{PRIMITIVES[t][0]}({value})"
    inner = vector_inner(t)
    if inner is not None:
        return f"Vector({value}, {writer(inner)})"
    return f"{value}.write()"


# --------------------------------------------------------------------------- #
# Code generation
# --------------------------------------------------------------------------- #

def gen_class(c: Combinator) -> str:
    fields = [a for a in c.args if not a.is_flags]

    required = [a for a in fields if not a.optional]
    optional = [a for a in fields if a.optional]

    bases = ["TLObject"]
    if not c.is_function:
        bases.insert(0, base_ref(c.result).replace("raw.base", "_base"))

    lines = []
    kind = "function" if c.is_function else "constructor"
    doc = f"Telegram API {kind} ``{c.tl_name}#{c.id:08x}``."
    if c.is_function:
        doc += f"\n\n    Returns: ``{c.result}``"
    else:
        doc += f"\n\n    Belongs to ``{c.result}``."

    lines.append(f"class {c.py_name}({', '.join(bases)}):")
    lines.append(f'    """{doc}\n    """')
    lines.append("")
    lines.append(f"    __slots__ = ({''.join(repr(a.py) + ', ' for a in fields)})")
    lines.append("")
    lines.append(f"    ID = 0x{c.id:08x}")
    lines.append(f'    QUALNAME = "{c.qualname}"')
    lines.append(f'    TL_NAME = "{c.tl_name}"')
    if c.is_function:
        lines.append(f'    RESULT = "{c.result}"')
    lines.append("")

    # __init__
    params = []
    for a in required:
        params.append(f"{a.py}: {hint(a.type)}")
    for a in optional:
        h = "bool" if a.type == "true" else hint(a.type)
        params.append(f"{a.py}: Optional[{h}] = None")
    sig = ", ".join(["self"] + (["*"] + params if params else []))
    lines.append(f"    def __init__({sig}) -> None:")
    if fields:
        for a in fields:
            lines.append(f"        self.{a.py} = {a.py}")
    else:
        lines.append("        pass")
    lines.append("")

    # read
    lines.append("    @staticmethod")
    lines.append(f'    def read(b: BytesIO, *args: Any) -> "{c.py_name}":')
    for a in c.args:
        if a.is_flags:
            lines.append(f"        f_{a.name} = Int.read(b)")
        elif a.optional:
            mask = f"f_{a.flag} & {1 << a.bit}"
            if a.type == "true":
                lines.append(f"        v_{a.py} = bool({mask})")
            else:
                lines.append(f"        v_{a.py} = {read_expr(a.type)} if {mask} else None")
        else:
            lines.append(f"        v_{a.py} = {read_expr(a.type)}")
    kw = ", ".join(f"{a.py}=v_{a.py}" for a in fields)
    lines.append(f"        return {c.py_name}({kw})")
    lines.append("")

    # write
    lines.append("    def write(self, *args: Any) -> bytes:")
    lines.append("        b = BytesIO()")
    lines.append("        b.write(Int(self.ID, False))")
    for a in c.args:
        if a.is_flags:
            members = [x for x in optional if x.flag == a.name]
            lines.append(f"        f_{a.name} = 0")
            for x in members:
                test = f"self.{x.py}" if x.type == "true" else f"self.{x.py} is not None"
                lines.append(f"        if {test}:")
                lines.append(f"            f_{a.name} |= {1 << x.bit}")
            lines.append(f"        b.write(Int(f_{a.name}))")
        elif a.optional:
            if a.type == "true":
                continue
            lines.append(f"        if self.{a.py} is not None:")
            lines.append(f"            b.write({write_expr(a.type, 'self.' + a.py)})")
        else:
            lines.append(f"        b.write({write_expr(a.type, 'self.' + a.py)})")
    lines.append("        return b.getvalue()")

    if c.is_function:
        lines.append("")
        lines.append("    def read_result(self, b: BytesIO) -> Any:")
        if c.generic:
            lines.append("        return read_result(b, self.query)")
        else:
            inner = vector_inner(c.result)
            if inner is not None:
                lines.append(f"        return read_result(b, None, {reader(inner)})")
            elif c.result in PRIMITIVES:
                lines.append(f"        return read_result(b, None, None, {PRIMITIVES[c.result][0]}.read)")
            else:
                lines.append("        return read_result(b)")

    return "\n".join(lines)


def module_header(layer: int, section: str) -> str:
    imports = [
        HEADER.format(layer=layer),
        "# flake8: noqa",
        "from __future__ import annotations",
        "",
        "from io import BytesIO",
        "from typing import TYPE_CHECKING, Any, List, Optional",
        "",
        "from wirelet.raw.core import (",
        "    TLObject, Int, Long, Int128, Int256, Double, String, Bytes, Bool, Vector,",
        "    read_result, write_object,",
        ")",
    ]
    if section == "types":
        imports.append("from wirelet.raw import base as _base")
    imports += [
        "",
        "if TYPE_CHECKING:",
        "    from wirelet import raw",
        "",
    ]
    return "\n".join(imports)


def gen_base_module(layer: int, names: Dict[str, List[str]], ns: str) -> str:
    out = [HEADER.format(layer=layer), "# flake8: noqa", ""]
    for name in sorted(names):
        members = ", ".join(sorted(names[name]))
        out.append(f"class {name}:")
        out.append(f'    """Abstract TL type ``{(ns + ".") if ns else ""}{name}``.')
        out.append("")
        out.append(f"    Constructors: {members}")
        out.append('    """')
        out.append("")
        out.append("    __slots__ = ()")
        out.append(f'    QUALNAME = "base.{(ns + ".") if ns else ""}{name}"')
        out.append("")
        out.append("")
    return "\n".join(out)


def write_package(pkg_dir: Path, modules: Dict[str, str], layer: int) -> None:
    pkg_dir.mkdir(parents=True, exist_ok=True)
    root = modules.pop("", None) or HEADER.format(layer=layer)
    subs = sorted(modules)

    init = root.rstrip() + "\n"
    if subs:
        init += f"\n\nfrom . import {', '.join(subs)}  # noqa: E402\n"
    (pkg_dir / "__init__.py").write_text(init)

    for name, body in modules.items():
        (pkg_dir / f"{name}.py").write_text(body)


def build() -> int:
    api = (SCHEMA_DIR / "api.tl").read_text(encoding="utf-8")
    mtproto = (SCHEMA_DIR / "mtproto.tl").read_text(encoding="utf-8")

    layer_match = LAYER_RE.search(api)
    if not layer_match:
        raise SystemExit("api.tl has no '// LAYER N' line")
    layer = int(layer_match.group(1))

    combinators: Dict[str, Combinator] = {}
    for c in parse(mtproto, "types", binary_strings=True) + parse(api, "types"):
        combinators[c.tl_name] = c  # api.tl wins on a clash

    # Detect Python name collisions inside one namespace.
    seen = {}
    for c in combinators.values():
        key = (c.section, c.namespace, c.py_name)
        if key in seen:
            raise SystemExit(f"Name clash: {c.tl_name} and {seen[key]} -> {key}")
        seen[key] = c.tl_name

    for sub in ("types", "functions", "base"):
        shutil.rmtree(OUT_DIR / sub, ignore_errors=True)

    # base
    base_types: Dict[str, Dict[str, List[str]]] = {}
    for c in combinators.values():
        if c.is_function:
            continue
        ns, short = split_ns(c.result)
        base_types.setdefault(ns, {}).setdefault(camel(short), []).append(c.py_name)

    base_modules = {ns: gen_base_module(layer, names, ns) for ns, names in base_types.items()}
    write_package(OUT_DIR / "base", base_modules, layer)

    # types / functions
    for section in ("types", "functions"):
        by_ns: Dict[str, List[Combinator]] = {}
        for c in combinators.values():
            if c.section == section:
                by_ns.setdefault(c.namespace, []).append(c)

        modules = {}
        for ns, items in by_ns.items():
            items.sort(key=lambda x: x.py_name)
            body = [module_header(layer, section)]
            body += [gen_class(c) + "\n\n" for c in items]
            modules[ns] = "\n\n".join(body)
        if "" not in modules:
            modules[""] = HEADER.format(layer=layer)
        write_package(OUT_DIR / section, modules, layer)

    # all.py: id -> qualname
    entries = sorted(combinators.values(), key=lambda c: c.id)
    all_lines = [HEADER.format(layer=layer), f"LAYER = {layer}", "", "OBJECTS = {"]
    for c in entries:
        all_lines.append(f'    0x{c.id:08x}: "{c.qualname}",')
    all_lines.append("}")
    (OUT_DIR / "all.py").write_text("\n".join(all_lines) + "\n")

    n_types = sum(1 for c in combinators.values() if not c.is_function)
    n_funcs = len(combinators) - n_types
    print(f"wirelet: generated layer {layer}: {n_types} types, {n_funcs} functions")
    return layer


if __name__ == "__main__":
    build()
